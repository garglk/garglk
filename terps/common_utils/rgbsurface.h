static const rgbsurf_font_t rgbsurf_font8x8 = { &rgbsurf_font8x8_rows[0][0], 8, 8 };
static const rgbsurf_font_t rgbsurf_font5x7 = { &rgbsurf_font5x7_rows[0][0], 5, 7 };

/* The columns glyph `c` actually uses, counted from the left: 0 for a blank
   glyph or a character the font does not have.  The basis for proportional
   spacing; each caller adds its own gap. */
static inline int
rgbsurf_glyph_cols (const rgbsurf_font_t *f, unsigned char c)
{
  int i, row, used = 0;
  if (c < 32 || c > 126)
    return 0;
  for (row = 0; row < f->h; row++)
    {
      unsigned char bits = f->rows[(c - 32) * f->h + row];
      for (i = f->w - 1; i >= 0; i--)
        if (bits & (1 << i))
          {
            if (i + 1 > used)
              used = i + 1;
            break;
          }
    }
  return used;
}

/* Draw glyph `c` with its top-left cell corner at (x,y); a character the
   font does not have draws nothing. */
static inline void
rgbsurf_draw_glyph (const rgbsurf_t *s, const rgbsurf_font_t *f,
                    unsigned char c, int x, int y, unsigned int rgb, int alpha)
{
  int row, col;
  if (c < 32 || c > 126)
    return;
  for (row = 0; row < f->h; row++)
    {
      unsigned char bits = f->rows[(c - 32) * f->h + row];
      for (col = 0; col < f->w; col++)
        if (bits & (1 << col))
          rgbsurf_blend (s, x + col, y + row, rgb, alpha);
    }
}

/* --- sending a surface to the window -------------------------------------

   Call `span` once for every horizontal run of one colour in `now`, row by
   row -- which a Glk caller turns into glk_window_fill_rect(win, rgb, x, y,
   len, 1).  Pass the surface last sent as `shown` to skip the rows that have
   not changed since; pass NULL when the window may no longer hold it (a
   fresh window, a resize, a redraw) and every row goes.  A `shown` of a
   different size counts as NULL. */
typedef void (*rgbsurf_span_fn) (void *ctx, unsigned int rgb, int x, int y,
                                 int len);

static inline void
rgbsurf_send (const rgbsurf_t *now, const rgbsurf_t *shown,
              rgbsurf_span_fn span, void *ctx)
{
  int x, y;
  if (shown != NULL &&
      (shown->px == NULL || shown->w != now->w || shown->h != now->h))
    shown = NULL;
  for (y = 0; y < now->h; y++)
    {
      const unsigned int *row = &now->px[(size_t) y * now->w];
      if (shown != NULL &&
          memcmp (row, &shown->px[(size_t) y * now->w],
                  (size_t) now->w * sizeof row[0]) == 0)
        continue;
      x = 0;
      while (x < now->w)
        {
          unsigned int c = row[x];
          int x0 = x;
          do
            x++;
          while (x < now->w && row[x] == c);
          span (ctx, c, x0, y, x - x0);
        }
    }
}

/* As rgbsurf_send, but merges a run with the same run (same x, width and
   colour) on the rows directly below it, so `rect` gets one w x h rectangle
   per vertical stack of identical runs rather than one call per row -- which
   a Glk caller turns into glk_window_fill_rect(win, rgb, x, y, w, h).  Box
   edges, link lines and flat fills in a map collapse to a handful of rects.

   The rectangles cover exactly the pixels rgbsurf_send's spans would, and no
   two overlap, so the order they arrive in does not matter; a merge never
   reaches across a row skipped as unchanged.  Falls back to one-row rects if
   it cannot allocate its bookkeeping. */
typedef void (*rgbsurf_rect_fn) (void *ctx, unsigned int rgb, int x, int y,
                                 int w, int h);

typedef struct
{
  int x, w, y0;
  unsigned int rgb;
} rgbsurf_open_run_t;

static inline void
rgbsurf_send_rects (const rgbsurf_t *now, const rgbsurf_t *shown,
                    rgbsurf_rect_fn rect, void *ctx)
{
  rgbsurf_open_run_t *open, *next, *swap;
  int nopen = 0, nnext, i, x, y;
  if (shown != NULL &&
      (shown->px == NULL || shown->w != now->w || shown->h != now->h))
    shown = NULL;
  if (now->w <= 0 || now->h <= 0)
    return;
  /* A row holds at most w runs. */
  open = (rgbsurf_open_run_t *) malloc ((size_t) now->w * sizeof *open);
  next = (rgbsurf_open_run_t *) malloc ((size_t) now->w * sizeof *next);
  if (open == NULL || next == NULL)
    {
      free (open);
      free (next);
      open = next = NULL;
    }
  for (y = 0; y < now->h; y++)
    {
      const unsigned int *row = &now->px[(size_t) y * now->w];
      if (shown != NULL &&
          memcmp (row, &shown->px[(size_t) y * now->w],
                  (size_t) now->w * sizeof row[0]) == 0)
        {
          /* An unchanged row ends every stack above it. */
          for (i = 0; i < nopen; i++)
            rect (ctx, open[i].rgb, open[i].x, open[i].y0, open[i].w,
                  y - open[i].y0);
          nopen = 0;
          continue;
        }
      /* Walk this row's runs against last row's open stacks; both are in x
         order and neither overlaps itself. */
      i = 0;
      nnext = 0;
      x = 0;
      while (x < now->w)
        {
          unsigned int c = row[x];
          int x0 = x;
          do
            x++;
          while (x < now->w && row[x] == c);
          if (open == NULL)
            {
              rect (ctx, c, x0, y, x - x0, 1);
              continue;
            }
          /* Stacks that started left of this run cannot continue. */
          while (i < nopen && open[i].x < x0)
            {
              rect (ctx, open[i].rgb, open[i].x, open[i].y0, open[i].w,
                    y - open[i].y0);
              i++;
            }
          if (i < nopen && open[i].x == x0 && open[i].w == x - x0
              && open[i].rgb == c)
            next[nnext++] = open[i++];
          else
            {
              next[nnext].x = x0;
              next[nnext].w = x - x0;
              next[nnext].y0 = y;
              next[nnext].rgb = c;
              nnext++;
            }
        }
      for (; i < nopen; i++)
        rect (ctx, open[i].rgb, open[i].x, open[i].y0, open[i].w,
              y - open[i].y0);
      swap = open;
      open = next;
      next = swap;
      nopen = nnext;
    }
  for (i = 0; i < nopen; i++)
    rect (ctx, open[i].rgb, open[i].x, open[i].y0, open[i].w,
          now->h - open[i].y0);
  free (open);
  free (next);
}

